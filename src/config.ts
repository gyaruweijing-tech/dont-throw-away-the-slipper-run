/** 1レベルの設定（§9 の難易度カーブ）。中身は CFG.levels にある */
export interface LevelSpec {
  /** 走行距離。runSpeed 9 なら 9m ≒ 1秒 */
  readonly length: number;
  /** 開始人数 */
  readonly start: number;
  /** このレベルで出してよい障害物。**空 ＝ 障害物なし** */
  readonly obstacles: readonly ObstacleKind[];
  /** 障害物を置き始める距離 */
  /**
   * ★**この距離から先に障害物を置く。**
   *
   * ★★**2026-09-15: 全レベル 18m にした**（本人の実機「**2区間に一つもギミックがない区間が
   * 連続しないっていうルールあったよね、それ、最初の2区間で出ていないことが多い**」）。
   * ★**実測（20走行×6レベル）で、全レベル 1区間目と2区間目の障害物が 0%** だった。
   * 35〜45m という値が、**最初の2区間をまるごと覆っていた**（ゲート間隔は平均 37m）。
   *
   * ★**`sim:density` が見逃していた理由もここにある** ―― あの検査は
   * 「`obstacleFrom` の手前は空きに数えない」と**自分で除外していた**ので、
   * **本人が見ている「最初がスカスカ」を、数字の上では合格と出していた**（検査の空振り）。
   * 2026-09-15 に検査のほうも直した。
   */
  readonly obstacleFrom: number;
  /** 間隔が足りているゲート間のうち、何割に障害物を置くか（§9 のカーブ） */
  readonly obstacleChance: number;
  /** 社員の初出距離。**null ＝ このレベルには出ない** */
  /** ゲートの型の解禁段階。0=素直/小損 → 1=+分岐点またぎ → 2=+罠/両損 → 3=全部 */
  readonly gateTier: number;
  /**
   * ゲート間隔の倍率（§11-7 ③・2026-08-24 追加）。**1 ＝ 従来どおり（平均37m）。**
   *
   * ★**復習回の「密度を上げる」ための唯一のつまみ。**
   * それまで密度は `GAP_CYCLE` に固定されていて全レベル共通だった。
   * 障害物を増やして密度を上げると**無双回ではなく鬼畜回**になるので（§11-9 #8）、
   * 上げるのは「得るもの＝ゲート」のほうにする。
   *
   * **下げすぎない。** 0.78 で最小間隔が 32→25m になる。`spawnAhead` 44 に対して
   * 同時に飛ぶ行が3行を超えるとプールが尽きる（`Gates.ts` の take が保険を持っているが、
   * 出ないゲートが発生する＝密度を上げたつもりで下がる）
   */
  readonly gateGap: number;
  /**
   * ゲートで割り込まれない人数の下限。**0 ＝ 0人まで行ける**（§4-E の原則）。
   * Lv1〜2 だけ 3 を入れて §9 の「失敗不可能」を担保する
   */
  readonly minCount: number;
  /**
   * 反対派の一団（§14-B-1）。距離の昇順で並べる。**空 ＝ 1体も出ない**。
   * 本家は赤い群れを道中に何度も置いている。うちも道中に2〜4回出し、
   * **一番大きい最後の1体がボス**（§4-F）になる。
   */
  readonly rivals: readonly { readonly at: number; readonly hp: number }[];
}

