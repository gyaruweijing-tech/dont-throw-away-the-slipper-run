/** 0〜1 に丸める。割合のつまみをモードが押し出さないための蓋 */
function unit(v: number): number {
  return v < 0 ? 0 : v > 1 ? 1 : v;
}

/**
 * ★★**そのレベルの設定をモード込みで返す**（2026-09-20）。
 *
 * ★**`CFG.levels[i]` を直に読まず、必ずここを通す。** 直に読むと
 * 「モードで効く数字と効かない数字」が混ざる ―― このリポジトリが
 * `resolveKnobs` を作ったときと同じ理由（`CFG` を上書きしない・2か所に書かない）。
 *
 * @param lv **0 始まり**の添字（`CFG.levels` の添字。`resolveKnobs` とは違うので注意）
 */
export function resolveLevel(lv: number, mode: GameMode = 'normal'): LevelSpec {
  const base = CFG.levels[lv];
  const m = MODES[mode];
  if (m.bossHp === 1 && m.rivalHp === 1 && m.gateGap === 1 && m.minGateTier === 0
    && m.obstacleChance === 0 && !m.bossHpByLevel) {
    return base;
  }
  const last = base.rivals.length - 1;
  /** ★表はレベル **1 始まり**。`lv` は 0 始まりの添字なので +1 して引く */
  const fixed = m.bossHpByLevel?.[lv + 1];
  return {
    ...base,
    gateTier: Math.max(base.gateTier, m.minGateTier),
    gateGap: base.gateGap * m.gateGap,
    obstacleChance: unit(base.obstacleChance + m.obstacleChance),
    /*
     * ★**ボスと道中の一団を分けて掛ける。** `rivals` の**最後の1体がボス**で、
     * 手前の `syain` や一団は道中の相手。同じ倍率を掛けると
     * **道中で人が尽きてボスに着けなくなる**（ボスを強くしたつもりが道中を強くしている）
     */
    rivals: base.rivals.map((r, i) => ({
      ...r,
      // ボス（最後の1体）は表があればその値。無ければ倍率。道中の一団はいつも倍率
      hp: i === last && fixed !== undefined
        ? fixed
        : Math.max(1, Math.round(r.hp * (i === last ? m.bossHp : m.rivalHp))),
    })),
  };
}

function checkKeys(part: Record<string, unknown> | undefined, base: Record<string, unknown>, where: string): void {
  if (!part) return;
  for (const k of Object.keys(part)) {
    if (!(k in base)) throw new Error(`[knobs] ${where} に知らないつまみ "${k}" が書かれている`);
  }
}

/**
 * **そのレベルで使う値を1つの表にして返す。**
 *
 * 順番は「`CFG` の既定値 → 区画の補間 → そのレベルの例外」。
 * @param lv **1 始まり**のレベル番号
 */
export function resolveKnobs(lv: number, mode: GameMode = 'normal'): { obstacle: ObstacleKnobs; gate: GateKnobs } {
  const obstacle: Record<string, number> = { ...CFG.obstacle };
  const gate: Record<string, number> = { ...CFG.gate };

  const zone = ZONES.find((z) => lv >= z.fromLv && lv <= z.toLv);
  if (zone) {
    checkKeys(zone.head.obstacle, obstacle, `区画「${zone.name}」head.obstacle`);
    checkKeys(zone.head.gate, gate, `区画「${zone.name}」head.gate`);
    checkKeys(zone.tail?.gate, gate, `区画「${zone.name}」tail.gate`);
    checkKeys(zone.tail?.obstacle, obstacle, `区画「${zone.name}」tail.obstacle`);
    // 区画の何本目か。1本だけの区画でも 0 除算しない
    const u = zone.toLv > zone.fromLv ? (lv - zone.fromLv) / (zone.toLv - zone.fromLv) : 0;
    for (const [k, v] of Object.entries(zone.head.obstacle ?? {})) {
      const to = zone.tail?.obstacle?.[k as keyof ObstacleKnobs];
      obstacle[k] = to === undefined ? v : lerp(v, to, u);
    }
    for (const [k, v] of Object.entries(zone.head.gate ?? {})) {
      const to = zone.tail?.gate?.[k as keyof GateKnobs];
      gate[k] = to === undefined ? v : lerp(v, to, u);
    }
  }

  const ex = LEVEL_TUNE[lv];
  if (ex) {
    checkKeys(ex.obstacle, obstacle, `Lv${lv} の例外 obstacle`);
    checkKeys(ex.gate, gate, `Lv${lv} の例外 gate`);
    Object.assign(obstacle, ex.obstacle ?? {});
    Object.assign(gate, ex.gate ?? {});
  }

  /*
   * ★★**4枚目 ＝ モード**（2026-09-20）。**区画とレベル例外のあとに掛ける。**
   * 先に掛けると `LEVEL_TUNE` がモードを打ち消すので、順番を入れ替えてはいけない。
   *
   * ★**足すのと掛けるのを分けている理由**: `hiddenChance` のような割合は
   * 区画によって 0 のこともあるので**掛けても何も起きない**。逆に `hiddenReveal` の
   * ような距離は**足すとレベルによって意味が変わる**（14m に +4 と 30m に +4 は別物）
   */
  const m = MODES[mode];
  checkKeys(m.gateAdd, gate, `モード「${m.name}」gateAdd`);
  checkKeys(m.gateScale, gate, `モード「${m.name}」gateScale`);
  for (const [k, v] of Object.entries(m.gateAdd ?? {})) {
    // 割合のつまみ（`*Chance`）だけは 0〜1 に丸める。それ以外は素直に足す
    gate[k] = k.endsWith('Chance') ? unit(gate[k] + v) : gate[k] + v;
  }
  for (const [k, v] of Object.entries(m.gateScale ?? {})) gate[k] = gate[k] * v;

  return {
    obstacle: obstacle as unknown as ObstacleKnobs,
    gate: gate as unknown as GateKnobs,
  };
}

/**
 * ★**プレイヤーが動ける半幅（m）。ここが唯一の計算場所。**
 *
 * 2026-08-28 に新設。それまで `Game.update` の中だけで計算していたので、
 * **ゲート側はプレイヤーがどこまで行けるかを知らないまま枠を置いていた**。
 * 「既定値に落ちる道を残さない」のと同じ理由で、**式を2か所に書かない**。
 *
 * @param radiusX 群れの見た目の横半径。太るほど動ける幅は狭くなる
 */
export function lateralHalfWidth(radiusX: number): number {
  return Math.max(CFG.minLateralRange, CFG.courseWidth / 2 - CFG.playableInset - radiusX * 0.8);
}

